-- Recipe and Pantry Manager: PostgreSQL database implementation
-- Run with psql against a database you own. This script is designed to be
-- rerunnable; DROP statements target only objects belonging to this project.

BEGIN;

CREATE TABLE IF NOT EXISTS users (
    user_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(120) NOT NULL,
    email           VARCHAR(254) NOT NULL UNIQUE,
    password_hash   TEXT NOT NULL,
    role            VARCHAR(20) NOT NULL DEFAULT 'student'
                    CHECK (role IN ('student', 'admin')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_email_format CHECK (position('@' IN email) > 1)
);

CREATE TABLE IF NOT EXISTS ingredients (
    ingredient_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(120) NOT NULL,
    category        VARCHAR(40) NOT NULL,
    unit            VARCHAR(30) NOT NULL,
    CONSTRAINT ingredients_name_category_unit_uk UNIQUE (name, category, unit),
    CONSTRAINT ingredients_category_ck CHECK
       (category IN ('veg', 'fruit', 'spice', 'dairy', 'grain', 'protein', 'oil', 'other'))
);

CREATE TABLE IF NOT EXISTS recipes (
    recipe_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(180) NOT NULL,
    description     TEXT NOT NULL DEFAULT '',
    cuisine         VARCHAR(80) NOT NULL,
    prep_time       INTEGER NOT NULL CHECK (prep_time > 0),
    created_by      BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT recipes_title_creator_uk UNIQUE (title, created_by)
);

CREATE TABLE IF NOT EXISTS recipe_ingredients (
    recipe_id       BIGINT NOT NULL REFERENCES recipes(recipe_id) ON DELETE CASCADE,
    ingredient_id   BIGINT NOT NULL REFERENCES ingredients(ingredient_id) ON DELETE RESTRICT,
    quantity        NUMERIC(10, 2) NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (recipe_id, ingredient_id)
);

CREATE TABLE IF NOT EXISTS pantry (
    pantry_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    ingredient_id   BIGINT NOT NULL REFERENCES ingredients(ingredient_id) ON DELETE RESTRICT,
    quantity        NUMERIC(10, 2) NOT NULL CHECK (quantity >= 0),
    expiry_date     DATE,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pantry_user_ingredient_expiry_uk UNIQUE (user_id, ingredient_id, expiry_date)
);

CREATE TABLE IF NOT EXISTS favorites (
    user_id         BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    recipe_id       BIGINT NOT NULL REFERENCES recipes(recipe_id) ON DELETE CASCADE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, recipe_id)
);

CREATE TABLE IF NOT EXISTS reviews (
    review_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    recipe_id       BIGINT NOT NULL REFERENCES recipes(recipe_id) ON DELETE CASCADE,
    rating          SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment         TEXT NOT NULL DEFAULT '',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT reviews_one_per_user_recipe_uk UNIQUE (user_id, recipe_id)
);

-- Supporting indexes for common joins, filters, sorting and text search.
CREATE INDEX IF NOT EXISTS recipes_cuisine_prep_idx ON recipes (cuisine, prep_time);
CREATE INDEX IF NOT EXISTS recipes_created_by_idx ON recipes (created_by);
CREATE INDEX IF NOT EXISTS recipe_ingredients_ingredient_idx ON recipe_ingredients (ingredient_id);
CREATE INDEX IF NOT EXISTS pantry_user_expiry_idx ON pantry (user_id, expiry_date);
CREATE INDEX IF NOT EXISTS pantry_ingredient_idx ON pantry (ingredient_id);
CREATE INDEX IF NOT EXISTS reviews_recipe_idx ON reviews (recipe_id);
CREATE INDEX IF NOT EXISTS recipes_search_idx ON recipes USING GIN
    (to_tsvector('english', title || ' ' || description || ' ' || cuisine));

-- Advanced feature 1: view reporting average rating and review count per recipe.
CREATE OR REPLACE VIEW recipe_rating_summary AS
SELECT r.recipe_id, r.title, r.cuisine, r.prep_time,
       COUNT(rv.review_id)::INTEGER AS review_count,
       ROUND(AVG(rv.rating)::NUMERIC, 2) AS average_rating
FROM recipes AS r
LEFT JOIN reviews AS rv ON rv.recipe_id = r.recipe_id
GROUP BY r.recipe_id, r.title, r.cuisine, r.prep_time;

-- Advanced feature 2: trigger keeps updated_at accurate on review edits.
CREATE OR REPLACE FUNCTION set_review_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS reviews_set_updated_at ON reviews;
CREATE TRIGGER reviews_set_updated_at
BEFORE UPDATE ON reviews
FOR EACH ROW EXECUTE FUNCTION set_review_updated_at();

-- Advanced feature 3: stored function returns recipes that can be made from
-- a user's unexpired pantry stock. Each needed ingredient must have a single
-- pantry lot with sufficient quantity; see query examples for partial lots.
CREATE OR REPLACE FUNCTION find_makeable_recipes(p_user_id BIGINT)
RETURNS TABLE (recipe_id BIGINT, title VARCHAR, cuisine VARCHAR, prep_time INTEGER)
LANGUAGE SQL STABLE AS $$
    SELECT r.recipe_id, r.title, r.cuisine, r.prep_time
    FROM recipes AS r
    WHERE EXISTS (SELECT 1 FROM recipe_ingredients ri WHERE ri.recipe_id = r.recipe_id)
      AND NOT EXISTS (
          SELECT 1
          FROM recipe_ingredients AS ri
          WHERE ri.recipe_id = r.recipe_id
            AND NOT EXISTS (
                SELECT 1 FROM pantry AS p
                WHERE p.user_id = p_user_id
                  AND p.ingredient_id = ri.ingredient_id
                  AND p.quantity >= ri.quantity
                  AND (p.expiry_date IS NULL OR p.expiry_date >= CURRENT_DATE)
            )
      )
    ORDER BY r.title;
$$;

